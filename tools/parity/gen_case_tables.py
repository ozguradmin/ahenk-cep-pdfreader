"""Write docs/js/trnorm/case_tables.js: the case properties of CPython 3.12 (Unicode 15.0) that str methods read.

The trnorm port must read text as CPython 3.12 does, the Python of Pyodide 0.27.7. JS engines carry their own,
newer Unicode data, and some assigned characters changed case properties after 15.0: U+1171E AHOM CONSONANT SIGN
MEDIAL RA is no longer case-ignorable (Unicode 16: V8, SpiderMonkey, JavaScriptCore), U+0295 ʕ no longer lowercase or
cased (Unicode 17: Safari 26's regex tables already). So the port does not ask the engine for them; these tables are
Python's, taken from Python itself (str.lower / islower / isupper and unicodedata.category on every code point):

  - SIGMA_IGNORABLE, SIGMA_CASED: the two classes str.lower()'s Final_Sigma rule (handle_capital_sigma) tells apart.
    It skips case-ignorable characters and then asks whether the next one is cased; a character that is both is
    skipped, so SIGMA_IGNORABLE is every case-ignorable character and SIGMA_CASED every cased one that is not.
  - LOWERCASE, UPPERCASE, TITLECASE: the Lowercase and Uppercase properties and category Lt, what str.islower() and
    str.isupper() test character by character.

Each table is a sorted list of code point ranges, written as base-36 numbers: for each range the gap after the
previous range and its length minus one (casing.js decodes them). Run with the Python whose Unicode version the port
pins:

    python3.12 tools/parity/gen_case_tables.py
"""

import pathlib
import sys
import unicodedata

OUT = pathlib.Path(__file__).resolve().parents[2] / 'docs' / 'js' / 'trnorm' / 'case_tables.js'


def ranges(pred):
    out, start = [], None
    for cp in range(0x110000):
        ok = not (0xD800 <= cp <= 0xDFFF) and pred(chr(cp))
        if ok and start is None:
            start = cp
        elif not ok and start is not None:
            out.append((start, cp - 1))
            start = None
    if start is not None:
        out.append((start, 0x10FFFF))
    return out


def b36(n):
    digits = '0123456789abcdefghijklmnopqrstuvwxyz'
    s = ''
    while True:
        n, r = divmod(n, 36)
        s = digits[r] + s
        if not n:
            return s


def encode(rs):
    prev, nums = -1, []
    for a, b in rs:
        nums += [b36(a - prev - 1), b36(b - a)]
        prev = b
    return ' '.join(nums)


def wrap(name, doc, rs):
    text = encode(rs)
    lines, line = [], ''
    for tok in text.split(' '):
        if len(line) + len(tok) + 1 > 112:
            lines.append(line)
            line = ''
        line += tok + ' '
    lines.append(line)
    lines[-1] = lines[-1].rstrip()
    body = ' +\n'.join(f"  '{ln}'" for ln in lines)
    return f'// {doc} ({len(rs)} ranges)\nexport const {name} =\n{body};\n'


def main():
    # (c + Σ).lower() ends in ς when c, read backwards from Σ, is a cased character that is not case-ignorable;
    # (Α + c + Σ) when c is case-ignorable (skipped, Α is cased) or cased
    cased = lambda c: (c + 'Σ').lower()[-1] == 'ς'  # noqa: E731
    ign_or_cased = lambda c: ('Α' + c + 'Σ').lower()[-1] == 'ς'  # noqa: E731
    tables = [
        ('SIGMA_IGNORABLE', 'case-ignorable characters', ranges(lambda c: ign_or_cased(c) and not cased(c))),
        ('SIGMA_CASED', 'cased characters that are not case-ignorable', ranges(cased)),
        ('LOWERCASE', 'Lowercase: str.islower() of the character alone', ranges(str.islower)),
        ('UPPERCASE', 'Uppercase: str.isupper() of the character alone', ranges(str.isupper)),
        ('TITLECASE', 'category Lt', ranges(lambda c: unicodedata.category(c) == 'Lt')),
    ]
    # the forward probe agrees: (ΑΣ + c) keeps σ exactly when c is cased and not case-ignorable
    assert ranges(lambda c: ('ΑΣ' + c).lower()[1] == 'σ') == tables[1][2]
    OUT.write_text(
        f'// Generated by tools/parity/gen_case_tables.py from CPython {sys.version.split()[0]} (unicodedata '
        f'{unicodedata.unidata_version}); do not edit.\n'
        '// Case properties as Python reads them, for casing.js; each table: base-36 numbers, for every code point\n'
        '// range the gap after the previous one and the length minus one.\n'
        f'export const UNICODE_VERSION = {unicodedata.unidata_version!r};\n'
        + ''.join(wrap(*t) for t in tables),
        encoding='utf-8',
    )
    print(f'{OUT}: ' + ', '.join(f'{n} {len(r)} ranges' for n, _, r in tables) + f', Unicode {unicodedata.unidata_version}')


if __name__ == '__main__':
    main()
