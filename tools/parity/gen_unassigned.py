"""Write docs/js/trnorm/unassigned.js: the code points Unicode 15.0 leaves unassigned, as a regex class.

The trnorm port (docs/js/trnorm) must read text exactly as CPython 3.12 does, the Python of Pyodide 0.27.7, whose
unicodedata is Unicode 15.0. A newer JS engine knows later characters (Unicode 16 added letters, digits, marks), so
normalize() hides those from it; see normalizer.js. Run with the Python whose Unicode version the port pins:

    python3.12 tools/parity/gen_unassigned.py
"""

import pathlib
import sys
import unicodedata

OUT = pathlib.Path(__file__).resolve().parents[2] / 'docs' / 'js' / 'trnorm' / 'unassigned.js'
# trnorm's emoji pattern removes these ranges by code point, assigned or not: they are left to it
EMOJI = [(0x1F000, 0x1FAFF), (0x1FC00, 0x1FFFD), (0x2600, 0x27BF), (0x2B00, 0x2BFF), (0x2300, 0x23FF),
         (0xFE0E, 0xFE0F), (0x20E3, 0x20E3)]


def main():
    ranges = []
    for cp in range(0x110000):
        if 0xD800 <= cp <= 0xDFFF or any(a <= cp <= b for a, b in EMOJI):
            continue
        if unicodedata.category(chr(cp)) == 'Cn':
            if ranges and ranges[-1][1] == cp - 1:
                ranges[-1][1] = cp
            else:
                ranges.append([cp, cp])
    parts = [('\\u{%x}' % a) if a == b else ('\\u{%x}-\\u{%x}' % (a, b)) for a, b in ranges]
    lines, line = [], ''
    for p in parts:
        if len(line) + len(p) > 110:
            lines.append(line)
            line = ''
        line += p
    lines.append(line)
    body = ' +\n'.join(f'  String.raw`{ln}`' for ln in lines)
    OUT.write_text(
        f'// Generated by tools/parity/gen_unassigned.py from CPython {sys.version.split()[0]} (unicodedata '
        f'{unicodedata.unidata_version}); do not edit.\n'
        '// The code points that Unicode version leaves unassigned (category Cn), outside the emoji ranges, as the inside\n'
        '// of a u-flag regex class.\n'
        f'export const UNICODE_VERSION = {unicodedata.unidata_version!r};\n'
        f'export const UNASSIGNED =\n{body};\n',
        encoding='utf-8',
    )
    print(f'{OUT}: {len(ranges)} ranges, Unicode {unicodedata.unidata_version}')


if __name__ == '__main__':
    main()
